"""Generates tests/zip_fixture.inc: a zip made by Python's zipfile (deflate + stored),
including path-traversal entries, so the C++ reader is tested against another tool."""
import io
import sys
import zipfile


def pattern(n, seed):
    return bytes(((i * 31 + (i >> 6) * seed) & 0xFF) for i in range(n))


buf = io.BytesIO()
with zipfile.ZipFile(buf, "w") as z:
    z.writestr(zipfile.ZipInfo("Pack/"), b"")
    z.writestr("Pack/Cat/123.dds", b"DDS " + pattern(20000, 3), compress_type=zipfile.ZIP_DEFLATED)  # dynamic Huffman
    z.writestr("Pack/456~blue.dds", b"DDS " + b"AB" * 150, compress_type=zipfile.ZIP_DEFLATED)
    z.writestr("Pack/789.dds", b"DDS " + pattern(64, 5), compress_type=zipfile.ZIP_STORED)
    z.writestr("Pack/notes.txt", b"not a texture", compress_type=zipfile.ZIP_DEFLATED)
    z.writestr("../evil.dds", b"DDS escape", compress_type=zipfile.ZIP_STORED)
    z.writestr("C:/evil2.dds", b"DDS escape", compress_type=zipfile.ZIP_STORED)
data = buf.getvalue()

out = sys.argv[1] if len(sys.argv) > 1 else "tests/zip_fixture.inc"
with open(out, "w", newline="\n") as f:
    f.write("// Generated by tools/gen_zip_fixture.py - do not edit.\n")
    f.write("static const unsigned char kFixtureZip[] = {\n")
    for i in range(0, len(data), 20):
        f.write(",".join(str(b) for b in data[i:i + 20]) + ",\n")
    f.write("};\n")
print(len(data), "bytes")
