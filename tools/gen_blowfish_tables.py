"""Generates core/blowfish_tables.inc.

Blowfish's initial P-array and S-boxes are the fractional hex digits of pi,
so we compute them instead of pasting 4 KB of magic numbers.
"""
import sys

WORDS = 18 + 4 * 256
HEX_DIGITS = WORDS * 8 + 16  # a few guard digits


def arctan_inv(x, one):
    total = term = one // x
    x2, n, sign = x * x, 1, 1
    while term:
        term //= x2
        n += 2
        sign = -sign
        total += sign * (term // n)
    return total


def pi_hex_fraction():
    one = 1 << (4 * HEX_DIGITS + 64)
    pi = 4 * (4 * arctan_inv(5, one) - arctan_inv(239, one))  # Machin
    frac = pi - 3 * one
    return frac >> 64  # now frac / 16**HEX_DIGITS


def main(out_path):
    frac = pi_hex_fraction()
    digits = format(frac, "x").rjust(HEX_DIGITS, "0")
    words = [int(digits[i * 8:i * 8 + 8], 16) for i in range(WORDS)]
    assert words[0] == 0x243F6A88 and words[18] == 0xD1310BA6, "pi digits wrong"
    with open(out_path, "w", newline="\n") as f:
        f.write("// Generated by tools/gen_blowfish_tables.py - do not edit.\n")
        f.write("static const uint32_t kInitP[18] = {\n")
        f.write(",".join(f"0x{w:08X}" for w in words[:18]) + "};\n")
        f.write("static const uint32_t kInitS[4][256] = {\n")
        for box in range(4):
            chunk = words[18 + box * 256:18 + (box + 1) * 256]
            f.write("{" + ",\n".join(",".join(f"0x{w:08X}" for w in chunk[r:r + 8]) for r in range(0, 256, 8)) + "},\n")
        f.write("};\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "core/blowfish_tables.inc")
